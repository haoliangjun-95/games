/** 按游戏名称取教程（GameShell 用 title 匹配） */
export function tutorialKeyForGameName(name: string): string | null {
  const map: Record<string, string> = {
    中国象棋: 'xiangqi',
    五子棋: 'gomoku',
    围棋: 'go',
    成语接龙: 'idiom',
    数独: 'sudoku',
    数字华容道: 'klotski',
    '24 点': 'game24',
    扫雷: 'minesweeper',
    '2048': 'g2048',
  }
  return map[name] ?? null
}

export function tutorialForGameName(name: string): TutorialStep[] | null {
  const key = tutorialKeyForGameName(name)
  return key ? (TUTORIALS[key] ?? null) : null
}
