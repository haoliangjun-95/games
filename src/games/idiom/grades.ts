const MERGED = new Map<Exclude<GradeId, 0>, string[]>()

/** 某年级的成语列表（年级专属词 + 接龙骨干，已去重；0 = null 表示全词库） */
export function gradeWords(grade: GradeId): string[] | null {
  if (grade === 0) return null
  let merged = MERGED.get(grade)
  if (!merged) {
    merged = [...new Set([...BANKS[grade]!, ...CHAIN_CORE])]
    MERGED.set(grade, merged)
  }
  return merged
}
